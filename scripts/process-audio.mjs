// Builds the whole sound set from its sources so the result is reproducible:
//   node scripts/process-audio.mjs [--only <id prefix>] [--no-report]
// 1. downloads the source recordings into .cache/audio (and unpacks the firearm library)
// 2. cuts, cleans, layers and synthesises each sound (scripts/audio/recipes-*.mjs)
// 3. encodes 44.1 kHz MP3 into public/assets/local/sounds
// 4. writes assets/sounds.json, src/audio/sound-meta.json and docs/audio-report.md
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fetchSources } from './audio/download.mjs';
import { duration, encodeMp3, LOOP_ROLL, writeWav } from './audio/dsp.mjs';
import { recipes, setSourcePaths } from './audio/kit.mjs';
import { measureAll } from './audio/measure.mjs';
import { FFSL_FILES, FREESOUND, ffslSource } from './audio/sources.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cacheDir = join(root, '.cache', 'audio');
const wavDir = join(cacheDir, 'wav');
const outDir = join(root, 'public', 'assets', 'local', 'sounds');
const log = (line) => process.stdout.write(`${line}\n`);
const onlyIndex = process.argv.indexOf('--only');
const only = onlyIndex >= 0 ? process.argv[onlyIndex + 1] : null;

const GENERATED = { license: 'CC0', author: 'Ironvale', title: 'synthesised', page: 'scripts/process-audio.mjs' };
const sourceInfo = (key) => (key === 'synth' ? GENERATED : (FREESOUND[key] ?? ffslSource(key)));

setSourcePaths(await fetchSources(cacheDir, log));
await import('./audio/recipes-weapons.mjs');
await import('./audio/recipes-world.mjs');
await import('./audio/recipes-grenade.mjs');
await import('./audio/recipes-ambience.mjs');

mkdirSync(wavDir, { recursive: true });
mkdirSync(outDir, { recursive: true });
const wanted = recipes.filter((recipe) => !only || recipe.id.startsWith(only));
if (!only) for (const file of readdirSync(outDir)) rmSync(join(outDir, file));

const built = [];
for (const recipe of wanted) {
  const name = recipe.id.replace(/^snd-/, '');
  let clip;
  try {
    clip = recipe.build();
  } catch (error) {
    throw new Error(`${recipe.id}: ${error.message}`);
  }
  if (recipe.stereo && clip.length === 1) clip = [clip[0], clip[0]];
  if (!recipe.stereo && clip.length === 2) throw new Error(`${recipe.id}: recipe is mono but built a stereo clip`);
  if (!(duration(clip) > 0.01)) throw new Error(`${recipe.id}: built an empty clip`);
  const wav = join(wavDir, `${name}.wav`);
  const file = join(outDir, `${name}.mp3`);
  writeWav(wav, clip);
  encodeMp3(wav, file, recipe.kbps);
  built.push({ recipe, name, file });
}
log(`built ${built.length} files`);
if (only) {
  const stats = await measureAll(built);
  for (const [i, item] of built.entries()) log(`${item.recipe.id} ${JSON.stringify(stats[i])}`);
  process.exit(0);
}

// ---------------------------------------------------------------- manifest and loop table
const assets = built.map(({ recipe, name }) => {
  const sources = recipe.sources.map(sourceInfo);
  const credited = sources.filter((source) => source.credit);
  return {
    id: recipe.id,
    kind: 'sound',
    license: credited[0]?.license ?? 'CC0',
    source: sources[0].page,
    ...(credited.length ? { credit: [...new Set(credited.map((source) => source.credit))].join('; ') } : {}),
    files: { audio: { path: `sounds/${name}.mp3`, local: true } },
  };
});
writeFileSync(join(root, 'assets', 'sounds.json'), `${JSON.stringify({ assets }, null, 1)}\n`);

const loops = Object.fromEntries(
  built.filter(({ recipe }) => recipe.loop).map(({ recipe }) => [recipe.id, { start: LOOP_ROLL, end: LOOP_ROLL + recipe.loop.body }]),
);
writeFileSync(
  join(root, 'src', 'audio', 'sound-meta.json'),
  `${JSON.stringify({ note: 'Generated by scripts/process-audio.mjs. Loop points in seconds.', loops }, null, 1)}\n`,
);

// ---------------------------------------------------------------- report
if (!process.argv.includes('--no-report')) {
  const stats = await measureAll(built);
  const totalBytes = built.reduce((sum, { file }) => sum + statSync(file).size, 0);
  const f = (value, digits = 1) => (Number.isFinite(value) ? value.toFixed(digits) : 'n/a');
  const rows = built.map(({ recipe, name, file }, i) => {
    const s = stats[i];
    const sources = [...new Set(recipe.sources.map((key) => (key === 'synth' ? 'synthesised' : `${sourceInfo(key).author}: ${sourceInfo(key).title}`)))].join(' + ');
    const loop = recipe.loop ? ` Loop ${recipe.loop.body} s, seam step ${f(s.seamStep)}.` : '';
    return `| ${name}.mp3 | ${recipe.stereo ? 2 : 1} | ${f(s.duration, 2)} | ${f(s.peakDb)} | ${f(s.truePeakDb)} | ${f(s.rmsDb)} | ${f(s.lufs)} | ${f(s.onsetMs, 0)} | ${s.centroidHz} | ${s.overs} | ${(statSync(file).size / 1024).toFixed(0)} | ${sources}.${loop}${recipe.note ? ` ${recipe.note}.` : ''} |`;
  });
  const counts = new Map();
  for (const { recipe } of built) for (const key of new Set(recipe.sources)) counts.set(key, (counts.get(key) ?? 0) + 1);
  const usedSources = [...counts].filter(([key]) => key !== 'synth').map(([key, count]) => ({ info: sourceInfo(key), count }));
  const synthCount = counts.get('synth') ?? 0;
  const unused = [...Object.keys(FREESOUND), ...Object.keys(FFSL_FILES)].filter((key) => !counts.has(key));
  if (unused.length) log(`sources downloaded but not used: ${unused.join(', ')}`);
  const flagged = built
    .map(({ name, recipe }, i) => ({ name, recipe, s: stats[i] }))
    // Tails fade in by design, so a late start is only a fault elsewhere.
    .filter(({ s, recipe, name }) => s.overs > 0 || (s.onsetMs > 12 && !name.endsWith('-tail')) || (recipe.loop && !(s.seamStep < 4)) || !Number.isFinite(s.lufs));
  const report = `# Audio report

Generated by \`node scripts/process-audio.mjs\`. Nobody has listened to these
files: every number below is measured from the encoded MP3, so a person can
audit by ear later and know where to start.

- Files: ${built.length}, ${(totalBytes / 1048576).toFixed(2)} MB in \`public/assets/local/sounds/\`
- Format: 44.1 kHz MP3 (LAME, constant bit rate): 128 kbps mono for one-shots, 160 kbps stereo for tails and beds, 96 kbps mono for positional loops
- Loops are periodic with ${LOOP_ROLL} s of the neighbouring cycle on each side; the engine loops between the points in \`src/audio/sound-meta.json\`, so decoder padding cannot open a gap. "Seam step" is the jump across the loop point in units of the signal's ordinary sample-to-sample step (about 1 is seamless, 5 or more would click)

## Columns

| Column | Meaning | Tool |
| --- | --- | --- |
| ch | channels | |
| dur | length in seconds after decoding | own decode |
| peak | highest sample, dBFS | ffmpeg astats |
| TP | true (inter-sample) peak, dBTP | ffmpeg loudnorm |
| RMS | RMS level of the whole file, dB | ffmpeg astats |
| LUFS | integrated loudness with 0.6 s of padding so short files gate properly | ffmpeg loudnorm |
| onset | milliseconds of silence (below -45 dB) before the sound starts | ffmpeg silencedetect |
| centroid | spectral centroid in Hz: higher is brighter | own FFT |
| overs | decoded samples above full scale (would clip in a fixed-point player) | own decode |
| kB | size on disk | |

## Worth a listen first

${flagged.length ? flagged.map(({ name, s, recipe }) => `- ${name}.mp3: ${[s.overs > 0 ? `${s.overs} samples over full scale` : '', s.onsetMs > 12 && !name.endsWith('-tail') ? `starts ${f(s.onsetMs, 0)} ms late` : '', recipe.loop && !(s.seamStep < 4) ? `loop seam step ${f(s.seamStep)}` : '', Number.isFinite(s.lufs) ? '' : 'loudness not measurable'].filter(Boolean).join(', ')}`).join('\n') : 'Nothing was flagged by the checks (samples over full scale, more than 12 ms of leading silence, a loop seam step of 4 or more, unmeasurable loudness).'}

## Sources

Every recording the set is built from. Freesound files are the public HQ MP3 previews.

| recording | author | licence | page | files built from it |
| --- | --- | --- | --- | --- |
${usedSources.map(({ info, count }) => `| ${info.title} | ${info.author} | ${info.license} | ${info.page} | ${count} |`).join('\n')}

${synthCount} files are synthesised in the script and use no recording.

## Every file

| file | ch | dur | peak | TP | RMS | LUFS | onset | centroid | overs | kB | built from |
| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |
${rows.join('\n')}
`;
  writeFileSync(join(root, 'docs', 'audio-report.md'), report);
  log(`report: docs/audio-report.md, total ${(totalBytes / 1048576).toFixed(2)} MB, ${flagged.length} flagged`);
}
